pub const CV182X_USB2_PHY_BASE: usize = 0x0300_6000;

// =============================================================================
// 0x0302_xxxx — GPIO
// =============================================================================


/// GPIO1 (GPIOB)，Active Domain
pub const GPIO1_BASE: usize = 0x0302_1000;



