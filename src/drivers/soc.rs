/// TOP 模块（系统顶层控制寄存器）
pub const TOP_BASE: usize = 0x0300_0000;

/// FMUX（引脚功能复用）
pub const FMUX_BASE: usize = 0x0300_1000;






/// 时钟发生器（`clock-controller`，`cvitek,cv181x-clk`）
pub const CLKGEN_BASE: usize = 0x0300_2000;




